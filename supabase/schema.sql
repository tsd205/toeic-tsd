-- TOEIC Vocabulary: Phase 1 database schema
-- Run this entire file in Supabase Dashboard > SQL Editor > New query.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'student'
    check (role in ('student', 'admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.tests (
  id bigint generated by default as identity primary key,
  title text not null unique,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.vocabulary (
  id bigint generated by default as identity primary key,
  test_id bigint not null references public.tests(id) on delete cascade,
  english text not null,
  pronunciation text,
  vietnamese text not null,
  word_type text,
  example text,
  created_at timestamptz not null default now()
);

create table if not exists public.attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  test_id bigint not null references public.tests(id),
  score integer not null default 0 check (score >= 0),
  total integer not null default 0 check (total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.attempts(id) on delete cascade,
  vocabulary_id bigint not null references public.vocabulary(id),
  submitted_english text,
  submitted_vietnamese text,
  is_correct boolean not null default false
);

create index if not exists vocabulary_test_id_idx on public.vocabulary(test_id);
create index if not exists attempts_user_id_idx on public.attempts(user_id);
create index if not exists attempt_answers_attempt_id_idx on public.attempt_answers(attempt_id);

-- Helper function: checks admin role without recursively triggering profile RLS.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
set row_security = off
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- Create a student profile automatically after signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Enable Row Level Security.
alter table public.profiles enable row level security;
alter table public.tests enable row level security;
alter table public.vocabulary enable row level security;
alter table public.attempts enable row level security;
alter table public.attempt_answers enable row level security;

-- Remove policies with these names first, so this script can be re-run.
drop policy if exists profiles_select_own_or_admin on public.profiles;
drop policy if exists tests_public_read on public.tests;
drop policy if exists tests_admin_all on public.tests;
drop policy if exists vocabulary_public_read on public.vocabulary;
drop policy if exists vocabulary_admin_all on public.vocabulary;
drop policy if exists attempts_select_own_or_admin on public.attempts;
drop policy if exists answers_select_own_or_admin on public.attempt_answers;

-- Profiles: a user can read their own profile; admins can read all.
create policy profiles_select_own_or_admin
on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

-- Do not grant client-side profile updates. Promote the first admin in SQL Editor only.

-- Published tests and vocabulary are readable by visitors.
create policy tests_public_read
on public.tests for select to anon, authenticated
using (is_active = true or (select public.is_admin()));

create policy tests_admin_all
on public.tests for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

create policy vocabulary_public_read
on public.vocabulary for select to anon, authenticated
using (
  exists (
    select 1 from public.tests t
    where t.id = vocabulary.test_id and t.is_active = true
  )
  or (select public.is_admin())
);

create policy vocabulary_admin_all
on public.vocabulary for all to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

-- History is private to its owner; admin can inspect all.
create policy attempts_select_own_or_admin
on public.attempts for select to authenticated
using (user_id = (select auth.uid()) or (select public.is_admin()));

create policy answers_select_own_or_admin
on public.attempt_answers for select to authenticated
using (
  exists (
    select 1 from public.attempts a
    where a.id = attempt_answers.attempt_id
      and (a.user_id = (select auth.uid()) or (select public.is_admin()))
  )
);

-- Explicit table grants. RLS remains the row-level security boundary.
grant select on public.tests, public.vocabulary to anon, authenticated;
grant insert, update, delete on public.tests, public.vocabulary to authenticated;
grant select on public.profiles, public.attempts, public.attempt_answers to authenticated;
grant usage, select on all sequences in schema public to authenticated;

